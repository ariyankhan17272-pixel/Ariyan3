module.exports.handleEvent = async function ({ api, event }) {
  const {
    threadID,
    messageID,
    body,
    senderID
  } = event;

  if (!body) return;

  const msg = body.toLowerCase().trim();

  // Nijum mention detection
  const mentions = event.mentions || {};

  for (const id of Object.keys(mentions)) {
    const name = String(mentions[id] || "").toLowerCase();

    if (
      name.includes("নিঝুম") ||
      name.includes("nijum")
    ) {
      return api.sendMessage(
        "𝐍𝐢𝐣𝐮𝐦-কে মেনশন করছোস নাকি? 😾 সাবধান, নিঝুম কিন্তু আমার বস 𝐀𝐫𝐢𝐲𝐚𝐧-এর কিউট সুন্দরী বউ 👑💗 বেশি নজর দিবি না কিন্তু 👀🔪",
        threadID,
        messageID
      );
    }
  }

  if (responses[msg]) {
    return api.sendMessage(
      responses[msg],
      threadID,
      (err, info) => {
        if (err || !info) return;

        if (!global.client.handleReply)
          global.client.handleReply = [];

        global.client.handleReply.push({
          name: module.exports.config.name,
          messageID: info.messageID,
          author: senderID,
          type: "sahu"
        });
      },
      messageID
    );
  }

  try {
    const base = await getMainAPI();

    const link =
      `${base}/simsimi?text=${encodeURIComponent(body)}`;

    const res = await axios.get(link);

    let reply = Array.isArray(res.data.response)
      ? res.data.response[0]
      : res.data.response;

    if (!reply) {
      reply =
        "𝐌𝐈𝐌 𝐁𝐨𝐭 বুঝতে পারে নাই 😭 আবার একটু সহজ করে বলো তো 🤣";
    }

    return api.sendMessage(
      reply,
      threadID,
      (err, info) => {
        if (err || !info) return;

        if (!global.client.handleReply)
          global.client.handleReply = [];

        global.client.handleReply.push({
          name: module.exports.config.name,
          messageID: info.messageID,
          author: senderID,
          type: "sahu"
        });
      },
      messageID
    );

  } catch {
    return api.sendMessage(
      "🙂 একটু পরে আবার বলো, 𝐌𝐈𝐌 𝐁𝐨𝐭 একটু 𝐁𝐮𝐬𝐲 😭🤣",
      threadID,
      messageID
    );
  }
};

module.exports.handleReply = async function ({
  api,
  event,
  handleReply
}) {
  if (event.senderID !== handleReply.author) return;

  try {
    const text = event.body.trim();

    const base = await getMainAPI();

    const link =
      `${base}/simsimi?text=${encodeURIComponent(text)}`;

    const res = await axios.get(link);

    const reply = Array.isArray(res.data.response)
      ? res.data.response[0]
      : res.data.response;

    if (!reply) return;

    return api.sendMessage(
      reply,
      event.threadID,
      (err, info) => {
        if (err || !info) return;

        if (!global.client.handleReply)
          global.client.handleReply = [];

        global.client.handleReply.push({
          name: module.exports.config.name,
          messageID: info.messageID,
          author: event.senderID,
          type: "sahu"
        });
      },
      event.messageID
    );

  } catch {
    return api.sendMessage(
      "🙂 একটু পরে আবার বলো, 𝐌𝐈𝐌 𝐁𝐨𝐭 একটু 𝐁𝐮𝐬𝐲 😭🤣",
      event.threadID,
      event.messageID
    );
  }
};

module.exports.run = async function ({ api, event }) {
  return module.exports.handleEvent({
    api,
    event
  });
};
