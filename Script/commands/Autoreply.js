/*
 * Global reply list
 */
if (!global.client.handleReply) {
  global.client.handleReply = [];
}

/*
 * Find matching auto reply
 */
function findResponse(text) {
  const msg = text.trim().toLowerCase();

  for (const group of responseGroups) {
    const keywords = group[0];
    const response = group[1];

    for (const keyword of keywords) {
      if (msg === keyword.toLowerCase()) {
        return response;
      }
    }
  }

  return null;
}

/*
 * Send message helper
 */
function sendReply(api, event, text) {
  return api.sendMessage(
    text,
    event.threadID,
    (err, info) => {
      if (err || !info) return;

      global.client.handleReply.push({
        name: module.exports.config.name,
        messageID: info.messageID,
        author: event.senderID,
        type: "sahu"
      });
    },
    event.messageID
  );
}

/*
 * Main event handler
 */
module.exports.handleEvent = async function ({ api, event }) {
  if (!event || !event.body) return;

  const text = event.body.trim();

  if (!text) return;

  /*
   * First check predefined auto replies
   */
  const response = findResponse(text);

  if (response) {
    return sendReply(api, event, response);
  }

  /*
   * If no predefined reply is found,
   * do nothing.
   */
  return;
};

/*
 * Handle replies to bot
 */
module.exports.handleReply = async function ({ api, event, handleReply }) {
  if (!event || !event.body) return;

  if (!handleReply) return;

  if (event.senderID !== handleReply.author) return;

  try {
    const text = event.body.trim();

    if (!text) return;

    const base = await getMainAPI();

    if (!base) {
      return api.sendMessage(
        "🙂 AI API পাওয়া যাচ্ছে না, একটু পরে আবার বলো",
        event.threadID,
        event.messageID
      );
    }

    const link = `${base}/simsimi?text=${encodeURIComponent(text)}`;

    const res = await axios.get(link, {
      timeout: 15000
    });

    const reply = Array.isArray(res.data.response)
      ? res.data.response[0]
      : res.data.response;

    if (!reply) {
      return api.sendMessage(
        "🙂 একটু পরে আবার বলো",
        event.threadID,
        event.messageID
      );
    }

    return api.sendMessage(
      reply,
      event.threadID,
      (err, info) => {
        if (err || !info) return;

        global.client.handleReply.push({
          name: module.exports.config.name,
          messageID: info.messageID,
          author: event.senderID,
          type: "sahu"
        });
      },
      event.messageID
    );

  } catch (error) {
    console.error("autoreplybot API Error:", error.message);

    return api.sendMessage(
      "🙂 একটু পরে আবার বলো",
      event.threadID,
      event.messageID
    );
  }
};

/*
 * Command run
 */
module.exports.run = async function ({ api, event }) {
  return module.exports.handleEvent({ api, event });
};
